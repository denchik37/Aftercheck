import {createHash} from 'node:crypto';
import {readFileSync, writeFileSync, readdirSync, mkdirSync, existsSync} from 'node:fs';
import {dirname, resolve} from 'node:path';
import {fileURLToPath} from 'node:url';
import ts from 'typescript';

const root = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const check = process.argv.includes('--check');
if (process.argv.slice(2).some(arg => arg !== '--check')) throw new Error('Usage: node scripts/build-browser.mjs [--check]');
if (ts.version !== '5.9.3') throw new Error('Browser compiler must match pinned TypeScript 5.9.3');
const sha256 = value => createHash('sha256').update(value).digest('hex');
const outputs = new Map();
const sources = new Map();
const allowed = new Set([
  'browser-engine', 'json-codec', 'evidence-core', 'verify-core', 'uniswap', 'policy',
  'values', 'report', 'amounts', 'token-precision', 'browser-export', 'browser-workspace'
]);

function compile(name) {
  if (sources.has(name)) return;
  if (!allowed.has(name)) throw new Error(`Unreviewed browser dependency: ${name}`);
  const sourcePath = `src/${name}.ts`;
  const source = readFileSync(resolve(root, sourcePath), 'utf8');
  sources.set(name, {path: sourcePath, sha256: sha256(source)});
  const result = ts.transpileModule(source, {
    fileName: sourcePath,
    reportDiagnostics: true,
    compilerOptions: {
      target: ts.ScriptTarget.ES2022,
      module: ts.ModuleKind.ESNext,
      rewriteRelativeImportExtensions: true,
      isolatedModules: true,
      removeComments: false,
      newLine: ts.NewLineKind.LineFeed
    }
  });
  const errors = result.diagnostics?.filter(d => d.category === ts.DiagnosticCategory.Error) ?? [];
  if (errors.length) throw new Error(ts.formatDiagnosticsWithColorAndContext(errors, {
    getCanonicalFileName: path => path, getCurrentDirectory: () => root, getNewLine: () => '\n'
  }));
  const output = result.outputText;
  // Inspect emitted runtime imports: erased type-only imports never publish Node
  // adapters. All dependencies must be explicitly reviewed local source modules.
  const tree = ts.createSourceFile(`${name}.js`, output, ts.ScriptTarget.ES2022, true, ts.ScriptKind.JS);
  const dependencies = [];
  function inspect(node) {
    if (ts.isImportDeclaration(node) || ts.isExportDeclaration(node)) {
      if (node.moduleSpecifier) {
        const specifier = node.moduleSpecifier.text;
        const match = /^\.\/([a-z-]+)\.js$/.exec(specifier);
        if (!match) throw new Error(`Nonlocal browser import in ${sourcePath}: ${specifier}`);
        dependencies.push(match[1]);
      }
    }
    if (ts.isCallExpression(node) && node.expression.kind === ts.SyntaxKind.ImportKeyword) {
      throw new Error(`Dynamic browser import is outside the publication boundary: ${sourcePath}`);
    }
    if (ts.isIdentifier(node) && ['Buffer', 'process', 'require'].includes(node.text)) {
      throw new Error(`Node runtime leaked into ${sourcePath}: ${node.text}`);
    }
    ts.forEachChild(node, inspect);
  }
  inspect(tree);
  outputs.set(`assets/${name}.js`, `// Generated by scripts/build-browser.mjs. Edit ${sourcePath}.\n${output}`);
  for (const dependency of dependencies) compile(dependency);
}

compile('browser-engine');
// The UI entry is integrated after the core parity checkpoint. Any present UI
// source participates in the same reproducibility and minimal-dependency gate.
if (existsSync(resolve(root, 'src/browser-workspace.ts'))) compile('browser-workspace');

const sourceList = [...sources.values()].sort((a, b) => a.path.localeCompare(b.path, 'en'));
const generatorDigest = sha256(readFileSync(fileURLToPath(import.meta.url)));
const buildInputs = {typescript: ts.version, generatorDigest, sources: sourceList};
const manifest = {
  schemaVersion: 'aftercheck.browser-build.v1',
  sourceDigest: sha256(JSON.stringify(buildInputs)),
  ...buildInputs,
  assets: [...outputs].sort(([a], [b]) => a.localeCompare(b, 'en')).map(([path, text]) => ({
    path, bytes: Buffer.byteLength(text, 'utf8'), sha256: sha256(text)
  }))
};
outputs.set('assets/browser-build.json', JSON.stringify(manifest, null, 2) + '\n');
const directory = resolve(root, 'web/assets');
mkdirSync(directory, {recursive: true});
const failures = [];
for (const [path, text] of outputs) {
  const file = resolve(root, 'web', path);
  if (check) {
    if (!existsSync(file) || readFileSync(file, 'utf8') !== text) failures.push(path);
  } else writeFileSync(file, text);
}
for (const filename of readdirSync(directory)) {
  if (!outputs.has(`assets/${filename}`)) failures.push(`unexpected assets/${filename}`);
}
if (failures.length) throw new Error(`Browser assets are stale or unreviewed: ${failures.join(', ')}`);
const total = [...outputs.values()].reduce((sum, text) => sum + Buffer.byteLength(text, 'utf8'), 0);
if (total > 250_000) throw new Error('Browser assets exceed the 250,000-byte publication budget');
console.log(`${check ? 'Verified' : 'Built'} ${outputs.size} browser assets, ${total} bytes; source digest ${manifest.sourceDigest}`);
